iptables="iptables"
fail2ban="fail2ban socklog-void"
SNT="net-tools network-manager wpasupplicant nm-tray network-manager-gnome lxpanel lxpolkit aria2 wget yt-dlp ${ntp} ${iptables} ${fail2ban}"
python="python3-full python3"
