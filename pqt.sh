C1="exfatprogs ntfs-3g dosfstools fatresize zfs-linux zfs-lts zfsbootmenu hfsprogs apfs-fuse apfsprogs e2fsprogs btrfs-progs ntfs2btrfs"
C2="fdisk parted gvfs usbtop smartmontools testdisk udisks2"
